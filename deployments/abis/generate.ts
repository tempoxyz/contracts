import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import type { Abi } from 'viem'

const root = new URL('../../earn/', import.meta.url)

/** Solidity files under one repository directory, recursively, sorted by file name. */
const solidityFiles = (directory: string, suffix: string) =>
  readdirSync(new URL(directory, root), { recursive: true, encoding: 'utf8' })
    .filter((path) => path.endsWith(suffix))
    .map((path) => ({ file: path.split('/').at(-1)!, path }))
    .sort((left, right) => (left.file < right.file ? -1 : 1))

/** `ERC4626Engine` → `erc4626Engine`, `PropAMMEngine` → `propAMMEngine`. */
const camel = (name: string) =>
  name.replace(/^[A-Z0-9]+(?=[A-Z][a-z])|^[A-Z]/, (prefix) => prefix.toLowerCase())

/**
 * Writes `generated.ts` from this repository's Foundry artifacts so TypeScript never hand-copies an
 * Earn contract ABI. Run `forge build src script test` first; pass `--check` to
 * fail when the committed module no longer matches the artifacts. Contracts from other
 * repositories belong in `external.ts`.
 *
 * Every deployable contract under `src/` (not an interface, library, or abstract contract) exports
 * `<name>Abi`, so a new contract or engine needs no entry here unless it is excluded or renamed.
 */
const sourceDirectories = ['core', 'engines', 'router', 'rewards', 'demo']
/** Core contracts lead in this order; every other contract follows its directory by file name. */
const leadingContracts = ['EarnVault', 'EarnFees', 'EarnFactory']
/** Export names that differ from the contract name. */
const aliases: Record<string, string> = { SingleZoneEarnRouter: 'earnRouterAbi' }
/** Contracts deployed only through Foundry, whose ABIs no TypeScript consumer calls. */
const excluded = [
  'DemoParPool',
  'DemoPropAMMParOracle',
  'DemoPropAMMRecipientRegistry',
  'EarnRewardsFactory',
  'SeededSimple4626Vault',
]

const sourceContracts = solidityFiles('src/', '.sol').flatMap(({ file, path }) => {
  const directory = sourceDirectories.indexOf(path.split('/')[0]!)
  const source = readFileSync(new URL(`src/${path}`, root), 'utf8')
  return [...source.matchAll(/^contract\s+(\w+)/gm)].map(([, contract]) => {
    if (directory < 0) throw new Error(`src/${path} is outside the exported source directories`)
    return { contract: contract!, directory, file }
  })
})
for (const contract of [...leadingContracts, ...Object.keys(aliases), ...excluded]) {
  if (!sourceContracts.some((source) => source.contract === contract)) {
    throw new Error(`${contract} is not a contract under src/`)
  }
}
const contracts = sourceContracts
  .filter(({ contract }) => !excluded.includes(contract))
  .sort((left, right) => {
    const rank = (contract: string) => {
      const index = leadingContracts.indexOf(contract)
      return index < 0 ? leadingContracts.length : index
    }
    return left.directory - right.directory || rank(left.contract) - rank(right.contract)
  })
  .map(({ contract, file }) => {
    const name = aliases[contract] ?? `${camel(contract)}Abi`
    return [name, `out/${file}/${contract}.json`] as const
  })

/**
 * Foundry scripts called with typed calldata; only their state-changing entry points are exported.
 * Every `<Name>.s.sol` deployment and fixture script exports `<name>ScriptAbi`.
 */
const scripts = ['script/deploy/', 'script/local/'].flatMap((directory) =>
  solidityFiles(directory, '.s.sol').map(({ file }) => {
    const script = file.slice(0, -'.s.sol'.length)
    const name = `${script[0]!.toLowerCase()}${script.slice(1)}ScriptAbi`
    return [name, `out/${file}/${script}Script.json`] as const
  }),
)

/**
 * Functions the deployment lifecycle calls on every engine regardless of kind: its asset, its
 * EarnVault binding, and two-step ownership. Every `src/engines/` contract named `<Name>Engine` must
 * expose them identically; generation fails otherwise, and `earnEngineBindingAbi` is the shared
 * subset.
 */
const engineBindingFunctions = [
  'asset',
  'earnVault',
  'initializeEarnVault',
  'owner',
  'pendingOwner',
  'transferOwnership',
  'acceptOwnership',
]

const header =
  '// Generated by `pnpm --filter @tempoxyz/earn abis` from Foundry artifacts; do not edit.\n'
const readAbi = (path: string) => {
  const { abi } = JSON.parse(readFileSync(new URL(path, root), 'utf8')) as { abi: Abi }
  if (!Array.isArray(abi) || abi.length === 0) throw new Error(`${path} has no ABI`)
  return abi
}
const contractAbis = contracts.map(([name, path]) => [name, readAbi(path)] as const)
const signature = (item: Abi[number]) =>
  item.type === 'function'
    ? `${item.name}(${item.inputs.map((input) => input.type).join(',')})`
    : item.type
const engineBindingAbi = (() => {
  const engines = contractAbis.filter(([name]) => name.endsWith('EngineAbi'))
  const bindings = engines.map(([engine, abi]) => {
    const items: Abi = abi
      .filter((item) => item.type === 'function' && engineBindingFunctions.includes(item.name))
      // Code-point order keeps the output independent of the runtime's locale.
      .sort((left, right) => (signature(left) < signature(right) ? -1 : 1))
    for (const name of engineBindingFunctions) {
      if (!items.some((item) => item.type === 'function' && item.name === name)) {
        throw new Error(`${engine} is missing engine binding function ${name}`)
      }
    }
    return [engine, items] as const
  })
  // Parameter names may differ; selectors, return types, and mutability may not.
  const shape = (items: Abi) =>
    JSON.stringify(
      items.map((item) =>
        item.type === 'function'
          ? [signature(item), item.outputs.map((output) => output.type), item.stateMutability]
          : item,
      ),
    )
  const [[, expected]] = bindings
  for (const [engine, items] of bindings) {
    if (shape(items) !== shape(expected)) {
      throw new Error(`${engine} engine binding functions differ from ${bindings[0]![0]}`)
    }
  }
  return expected
})()
// Compact JSON keeps the output independent of formatter versions.
const body = [
  ...contractAbis,
  ['earnEngineBindingAbi', engineBindingAbi] as const,
  ...scripts.map(([name, path]) => {
    const entryPoints = readAbi(path).filter(
      (item) => item.type === 'function' && item.stateMutability === 'nonpayable',
    )
    if (entryPoints.length === 0) throw new Error(`${path} has no entry point`)
    return [name, entryPoints] as const
  }),
]
  .map(([name, abi]) => `export const ${name} = ${JSON.stringify(abi)} as const\n`)
  .join('\n')
const output = header + '\n' + body
const target = fileURLToPath(new URL('generated.ts', import.meta.url))

if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) {
    throw new Error(
      'Contract ABIs drifted; run `pnpm --filter @tempoxyz/earn abis` after `forge build src script test`',
    )
  }
} else {
  writeFileSync(target, output)
}
