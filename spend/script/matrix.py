#!/usr/bin/env python3
"""Run the card E2E matrix and write the scenario x setup capability table.

Usage: python3 script/matrix.py [--out ../docs/spend/matrix.md]
"""

import argparse
import json
import os
import re
import subprocess
import sys
from collections import OrderedDict

SETUPS = OrderedDict(
    [
        ("Bridge_EA_Stablecoin", "Bridge EA<br>stablecoin"),
        ("Bridge_P2_Stablecoin", "Bridge P2<br>stablecoin"),
        ("Bridge_TF_Stablecoin", "Bridge TF<br>stablecoin"),
        ("Bridge_TF_Earn", "Bridge TF<br>Earn"),
        ("Bridge_EV_Earn", "Bridge EV (PR #14)<br>ERC-4626"),
        ("Tempo_AccessKey_Stablecoin", "Tempo TS, access key<br>stablecoin"),
        ("Tempo_AccessKey_Earn", "Tempo TS, access key<br>Earn"),
        ("Tempo_Private_Stablecoin", "Tempo TS, private<br>stablecoin"),
        ("Tempo_Private_Earn", "Tempo TS, private<br>Earn"),
        ("Tempo_PrivateClosedLoop_Stablecoin", "Tempo TS, private closed loop<br>stablecoin"),
        ("Tempo_PrivateClosedLoop_Earn", "Tempo TS, private closed loop<br>Earn"),
    ]
)


def run_forge():
    proc = subprocess.run(
        ["forge", "test", "--match-path", "test/e2e/Matrix.t.sol", "--json", "-vv"],
        capture_output=True,
        text=True,
    )
    start = proc.stdout.find("{")
    if start < 0:
        sys.stderr.write(proc.stdout + proc.stderr)
        sys.exit(1)
    return json.loads(proc.stdout[start:])


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default="../docs/spend/matrix.md")
    args = parser.parse_args()

    results = run_forge()
    cells = {}
    gaps = {}
    scenarios = []
    failures = 0
    for suite, data in results.items():
        setup = suite.split(":")[-1]
        if setup not in SETUPS:
            sys.exit(f"unknown test suite {suite}: add {setup} to SETUPS in script/matrix.py")
        for name, result in data["test_results"].items():
            scenario = re.sub(r"\(.*\)$", "", name)
            if scenario not in scenarios:
                scenarios.append(scenario)
            status = result["status"]
            notes = [
                line[len("GAP: ") :]
                for line in result.get("decoded_logs", [])
                if line.startswith("GAP: ")
            ]
            if status == "Skipped":
                cell = "n/a"
            elif status != "Success":
                cell = "FAIL"
                failures += 1
            elif notes:
                cell = "gap"
                gaps.setdefault(scenario, {})[setup] = notes[0]
            else:
                cell = "pass"
            cells[(scenario, setup)] = cell

    scenarios.sort()
    lines = [
        "# Card scenario matrix",
        "",
        "Generated by `python3 script/matrix.py` from `forge test --match-path test/e2e/Matrix.t.sol`.",
        "`pass` meets the product behavior, `gap` passes by pinning a known shortfall (listed below),",
        "`n/a` does not apply to that setup. For the Tempo setups, the off-chain retry and stablecoin",
        "refund gaps are decided (decisions 3 and 4 in `docs/spend/design.md`), and the leaked Zone key gap",
        "is accepted risk (decision 7).",
        "",
        "| Scenario | " + " | ".join(SETUPS.values()) + " |",
        "| --- | " + " | ".join("---" for _ in SETUPS) + " |",
    ]
    for scenario in scenarios:
        row = [cells.get((scenario, s), "") for s in SETUPS]
        lines.append(f"| `{scenario.removeprefix('test_')}` | " + " | ".join(row) + " |")
    lines += ["", "## Gaps", ""]
    for scenario in sorted(gaps):
        for setup, note in gaps[scenario].items():
            label = SETUPS[setup].replace("<br>", " ")
            lines.append(f"- `{scenario.removeprefix('test_')}`, {label}: {note}.")
    lines.append("")

    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    with open(args.out, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {args.out}: {len(scenarios)} scenarios x {len(SETUPS)} setups, {failures} failures")
    sys.exit(1 if failures else 0)


if __name__ == "__main__":
    main()
